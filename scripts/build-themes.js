// Rules whose EVO role differs from the role of their Evro color, keyed by the
// rule's first scope selector. Scopes themselves are never changed.
const scopeRoleOverrides = {
  // Types and classes get their own color instead of sharing the function color.
  'entity.name.type': 'type',
  'entity.name.class': 'type',
  'support.class': 'type',
  // Symbolic operators are short glyphs: a magenta accent without flooding.
  'keyword.operator': 'operator',
  'source.js keyword.operator': 'operator',
  'source.ts keyword.operator': 'operator',
  'source.flow keyword.operator': 'operator',
  'source.js.embedded.html keyword.operator': 'operator',
  'keyword.operator.increment.js': 'operator',
  // Numbers and colors use the constant color rather than the string color.
  'constant.numeric': 'constant',
  'constant.numeric.decimal.js': 'constant',
  'constant.other.color': 'constant',
};

function alpha(hex, a) {
  return hex + a;
}

function remapTokenColors(rules, syntax, sourceFile) {
  return rules.map((rule, index) => {
    const settings = { ...rule.settings };
    if (settings.foreground) {
      const original = settings.foreground.toUpperCase();
      const base = original.slice(0, 7);
      const suffix = original.slice(7);
      const firstScope = Array.isArray(rule.scope) ? rule.scope[0] : String(rule.scope).split(',')[0].trim();
      const role = scopeRoleOverrides[firstScope] || evroColorRoles[base];
      if (!role) {
        throw new Error(`${sourceFile}: tokenColors[${index}] uses unmapped color ${settings.foreground}`);
      }
      // Evro's mint #76ECB7D5 alpha is dropped; other alpha suffixes are kept.
      const keepAlpha = suffix && base !== '#76ECB7';
      settings.foreground = keepAlpha ? syntax[role] + suffix : syntax[role];
    }
    return { ...rule, settings };
  });
}

function semanticTokenColors(s) {
  return {
    keyword: s.keyword,
    type: s.type,
    class: s.type,
    interface: s.type,
    enum: s.type,
    struct: s.type,
    typeParameter: { foreground: s.type, italic: true },
    namespace: s.textMuted,
    function: s.function,
    method: s.function,
    macro: s.function,
    decorator: s.operator,
    property: s.property,
    variable: s.textMuted,
    parameter: s.textMuted,
    'variable.readonly': s.constant,
    enumMember: s.constant,
    number: s.constant,
    string: s.string,
    regexp: s.type,
    operator: s.operator,
    comment: { foreground: s.comment, italic: true },
    // Diagnostics: deprecated symbols are struck through. Error, warning, info and
    // hint squiggles use the editorError/Warning/Info/Hint workbench colors.
    '*.deprecated': { strikethrough: true },
  };
}

